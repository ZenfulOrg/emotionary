#!/usr/bin/env node
/**
 * Copies the daily-word engine and notification wording into the Edge
 * Functions' shared folder, so the push server picks exactly the same word
 * (deck rotation) and writes exactly the same text as the app.
 *
 * Usage: node scripts/sync-push-shared.mjs [--check]
 *   --check  exit 1 if the copies are out of date (used by the tests)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const HEADER = '// GENERATED by scripts/sync-push-shared.mjs from the app source. Do not edit.\n';

export function sharedFiles() {
  const read = (p) => readFileSync(join(root, p), 'utf8');
  const word = "import type { Word } from './word.ts';";
  return {
    'supabase/functions/_shared/daily-engine.ts':
      HEADER + read('src/daily/engine.ts').replace("import type { Word } from '@/content/types';", word),
    'supabase/functions/_shared/notification-content.ts':
      HEADER +
      read('src/notifications/content.ts')
        .replace("import type { Word } from '@/content/types';", word)
        .replace("from '@/daily/engine';", "from './daily-engine.ts';"),
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  let stale = false;
  for (const [path, content] of Object.entries(sharedFiles())) {
    const full = join(root, path);
    let current = '';
    try {
      current = readFileSync(full, 'utf8');
    } catch {}
    if (current === content) continue;
    stale = true;
    if (!check) {
      writeFileSync(full, content);
      console.log(`updated ${path}`);
    }
  }
  if (check && stale) {
    console.error('Shared push files are out of date. Run: node scripts/sync-push-shared.mjs');
    process.exit(1);
  }
}
